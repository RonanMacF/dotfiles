-- Auto-generate pyrightconfig.json from $VIRTUAL_ENV + pyproject.toml extraPaths.
-- pyrightconfig.json overrides pyproject.toml entirely, so we must merge extraPaths.
-- The file is added to .git/info/exclude so it's never committed.
vim.api.nvim_create_autocmd("FileType", {
  pattern = "python",
  callback = function(ev)
    local venv = vim.env.VIRTUAL_ENV
    if not venv or venv == "" or vim.fn.isdirectory(venv) == 0 then return end

    local fname = vim.api.nvim_buf_get_name(ev.buf)
    if fname == "" then return end
    local git_root = require("lspconfig.util").find_git_ancestor(fname)
    if not git_root then return end

    local out_path = git_root .. "/pyrightconfig.json"
    local venv_path = vim.fn.fnamemodify(venv, ":h")
    local venv_name = vim.fn.fnamemodify(venv, ":t")

    -- Skip if already up to date
    if vim.fn.filereadable(out_path) == 1 then
      local ok, cfg = pcall(vim.json.decode, table.concat(vim.fn.readfile(out_path), "\n"))
      if ok and cfg.venvPath == venv_path and cfg.venv == venv_name then return end
    end

    -- Extract extraPaths from pyproject.toml via Python's tomllib (3.11+ stdlib)
    local extra_paths = {}
    local pyproject = git_root .. "/pyproject.toml"
    if vim.fn.filereadable(pyproject) == 1 then
      local py = venv .. "/bin/python3"
      if vim.fn.executable(py) ~= 1 then py = vim.fn.exepath("python3") end
      local script = string.format(
        "import tomllib,json; d=tomllib.load(open('%s','rb')); print(json.dumps(d.get('tool',{}).get('pyright',{}).get('extraPaths',[])))",
        pyproject)
      local r = vim.fn.system({ py, "-c", script })
      local ok2, paths = pcall(vim.json.decode, (r:gsub("\n", "")))
      if ok2 and type(paths) == "table" then extra_paths = paths end
    end

    local f = io.open(out_path, "w")
    if not f then return end
    f:write(vim.fn.json_encode({
      venvPath = venv_path,
      venv = venv_name,
      extraPaths = extra_paths,
      reportAny = "none",
      reportUnknownVariableType = "none",
      reportUnknownMemberType = "none",
      reportUnknownArgumentType = "none",
      reportUnknownParameterType = "none",
      reportUnknownLambdaType = "none",
    }))
    f:close()

    -- Keep out of git via local exclude
    local exclude = git_root .. "/.git/info/exclude"
    if vim.fn.filereadable(exclude) == 1 then
      local content = table.concat(vim.fn.readfile(exclude), "\n")
      if not content:find("pyrightconfig%.json") then
        vim.fn.writefile({ "", "# generated by nvim", "pyrightconfig.json" }, exclude, "a")
      end
    end

    -- Restart basedpyright so it picks up the new config
    for _, client in ipairs(vim.lsp.get_clients({ name = "basedpyright" })) do
      vim.lsp.stop_client(client.id)
    end
  end,
})

return {
  {
    "neovim/nvim-lspconfig",
    opts = {
      codelens = { enabled = true },
      servers = {
        basedpyright = {
          handlers = {
            ["$/progress"] = function() end,
          },
          root_dir = function(bufnr, on_dir)
            local fname = vim.api.nvim_buf_get_name(bufnr)
            local util = require("lspconfig.util")
            on_dir(util.find_git_ancestor(fname)
              or util.root_pattern("pyrightconfig.json", "pyproject.toml")(fname))
          end,
          settings = {
            basedpyright = {
              analysis = {
                typeCheckingMode = "standard",
                autoSearchPaths = true,
                useLibraryCodeForTypes = true,
                autoImportCompletions = true,
                diagnosticMode = "openFilesOnly",
              },
            },
          },
        },
      },
    },
  },
}
